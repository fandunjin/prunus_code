#!/bin/bash
# Adapt the scheduler header to your cluster (SLURM, PBS, JSUB, ...).
TRANS_DIR="${TRANS_DIR:-${DATA_DIR}/transcriptome_32}"
GENOME_FA="${GENOME_FA:-${DATA_DIR}/haphic/merge/04.build/final_assembly_qc_outputs/psp_2n32.chromosomes.fa}"
EVIDENCE_DIR="${DATA_DIR}/annotation/genes/psp32_eviann/evidence"
OUT_DIR="${DATA_DIR}/annotation/genes/psp32_eviann"
POST_DIR="${OUT_DIR}/postprocess"
EVIDENCE_TRANSCRIPTS="${EVIDENCE_TRANSCRIPTS:-${EVIDENCE_DIR}/psp_illumina.transcripts.fa}"
EVIDENCE_GTF="${EVIDENCE_GTF:-${EVIDENCE_DIR}/psp_illumina.transcripts.gtf}"
READS_LIST="${READS_LIST:-${EVIDENCE_DIR}/psp_eviann_reads.txt}"
EVIANN_TRANSCRIPTS="${EVIANN_TRANSCRIPTS:-${EVIDENCE_DIR}/psp_target_plus_pzi.transcripts.fa}"
HELIXER_GFF="${HELIXER_GFF:-${DATA_DIR}/annotation/genes/psp32_helixer_edta_masked/psp_2n32.chromosomes.edta_masked.helixer.gff3}"
TE_GFF3="${TE_GFF3:-${DATA_DIR}/annotation/repeats/chr32_edta/psp_2n32.chromosomes.fa.mod.EDTA.TEanno.gff3}"
PREFIX="psp32.eviann"
THREADS="${THREADS:-32}"
FORCE="${FORCE:-0}"
CONDA_SH="${CONDA_SH:-${CONDA_ROOT}/etc/profile.d/conda.sh}"
EVIANN_ENV="${EVIANN_ENV:-eviann}"
PY_ENV="${PY_ENV:-haphic}"
USE_PROTEINS="${USE_PROTEINS:-1}"
USE_SWISSPROT="${USE_SWISSPROT:-0}"
PLOIDY="${PLOIDY:-4}"
SWISSPROT="${SWISSPROT:-${HOME}/CX/database/SwissProt/uniprot_sprot.fasta}"
POSTPROCESS_SCRIPT="${POSTPROCESS_SCRIPT:-${ROOT_DIR}/scripts/helixer_postprocess_qc.py}"
STATS_SCRIPT="${STATS_SCRIPT:-${ROOT_DIR}/scripts/gff3_basic_stats.py}"

# PZI transcript evidence is generated by the PZI transcriptome jobs before
# this job is submitted. The protein set is deliberately identical to PZI's.
RELATED_TRANSCRIPTS="${RELATED_TRANSCRIPTS:-${ROOT_DIR}/annotation/genes/pzi_eviann/evidence/pzi_illumina_pacbio.transcripts.fa}"
PROTEIN_EVIDENCE_DEFAULT="${EVIDENCE_DIR}/ppe_pcam.proteins.fa"
RELATED_PROTEINS="${RELATED_PROTEINS:-${PROTEIN_EVIDENCE_DEFAULT}}"
RELATED_PROTEIN_SOURCES=(
    "${ROOT_DIR}/data/ppe/GCF_000346465.2_Prunus_persica_NCBIv2_protein.faa.gz"
    "${ROOT_DIR}/data/pcam/GCA_050084535.1_PCAv2.0_protein.faa.gz"
)
RELATED_PROTEIN_LABELS=(ppe pcam)

die() { echo "ERROR: $*" >&2; exit 1; }
require_file() { [[ -s "$1" ]] || die "$2 does not exist or is empty: $1"; }
require_cmd() { command -v "$1" >/dev/null 2>&1 || die "Required command not found: $1"; }

case "${USE_PROTEINS}" in
    0|1) ;;
    *) die "USE_PROTEINS must be 0 or 1 (observed: ${USE_PROTEINS})" ;;
esac
case "${USE_SWISSPROT}" in
    0|1) ;;
    *) die "USE_SWISSPROT must be 0 or 1 (observed: ${USE_SWISSPROT})" ;;
esac
[[ "$PLOIDY" =~ ^[1-9][0-9]*$ ]] || die "PLOIDY must be a positive integer (observed: $PLOIDY)"

append_fasta() {
    local source="$1" target="$2"
    [[ -s "$source" ]] || return 1
    if [[ "$source" == *.gz ]]; then gzip -dc "$source" >> "$target"; else cat "$source" >> "$target"; fi
}

append_prefixed_fasta() {
    local source="$1" prefix="$2" target="$3"
    if [[ "$source" == *.gz ]]; then gzip -dc "$source"; else cat "$source"; fi \
        | awk -v prefix="$prefix" '/^>/{sub(/^>/, ">" prefix "|")} {print}' >> "$target"
}

build_related_evidence() {
    if [[ "$USE_PROTEINS" == 1 && "$RELATED_PROTEINS" == "$PROTEIN_EVIDENCE_DEFAULT" ]]; then
        : > "$RELATED_PROTEINS"
        for i in "${!RELATED_PROTEIN_SOURCES[@]}"; do
            source="${RELATED_PROTEIN_SOURCES[$i]}"
            append_prefixed_fasta "$source" "${RELATED_PROTEIN_LABELS[$i]}" "$RELATED_PROTEINS" \
                || die "missing PPE/PCAM protein source: $source"
        done
    fi
    require_file "$RELATED_TRANSCRIPTS" "PZI transcript evidence for PSP"
    require_file "$EVIDENCE_TRANSCRIPTS" "PSP genome-guided transcript evidence"
    local combined_tmp="${EVIANN_TRANSCRIPTS}.tmp.$$"
    : > "$combined_tmp"
    # Keep the assembled PSP models and add reciprocal PZI transcripts as the
    # related-species evidence.
    append_prefixed_fasta "$EVIDENCE_TRANSCRIPTS" "psp" "$combined_tmp"
    append_prefixed_fasta "$RELATED_TRANSCRIPTS" "pzi" "$combined_tmp"
    mv -f "$combined_tmp" "$EVIANN_TRANSCRIPTS"
    require_file "$EVIANN_TRANSCRIPTS" "combined PSP target plus PZI transcript evidence"
    if [[ "$USE_PROTEINS" == 1 ]]; then require_file "$RELATED_PROTEINS" "PPE+PCAM protein evidence"; fi
}

build_reads_list() {
    local tmp="${READS_LIST}.tmp.$$"
    : > "$tmp"
    for lib in leaf root stem; do
        local r1="${TRANS_DIR}/01.clean_data/${lib}_clean_R1.fq.gz"
        local r2="${TRANS_DIR}/01.clean_data/${lib}_clean_R2.fq.gz"
        require_file "$r1" "PSP cleaned Illumina R1 ${lib}"
        require_file "$r2" "PSP cleaned Illumina R2 ${lib}"
        printf '%s %s\n' "$r1" "$r2" >> "$tmp"
    done
    mv -f "$tmp" "$READS_LIST"
}

require_file "$GENOME_FA" "PSP 2n=32 genome FASTA"
require_file "$HELIXER_GFF" "PSP Helixer GFF3"
require_file "$TE_GFF3" "PSP EDTA TE annotation GFF3"
require_file "$CONDA_SH" "Conda initialization script"
require_file "$POSTPROCESS_SCRIPT" "postprocess/QC script"
require_file "$STATS_SCRIPT" "GFF3 statistics script"
mkdir -p "$EVIDENCE_DIR" "$OUT_DIR" "$POST_DIR" "${ROOT_DIR}/logs"

source "$CONDA_SH"
conda activate "$EVIANN_ENV"
require_cmd eviann.sh
build_related_evidence
build_reads_list

RAW_GFF="$OUT_DIR/$(basename "$GENOME_FA").pseudo_label.gff"
FUNCTIONAL_GFF="$OUT_DIR/$(basename "$GENOME_FA").functional_note.pseudo_label.gff"
echo "=== EviAnn PSP 2n=32 annotation ==="
echo "Genome     : $GENOME_FA"
echo "Reads list : $READS_LIST"
echo "EviAnn tx  : $EVIANN_TRANSCRIPTS"
echo "Related tx : $RELATED_TRANSCRIPTS"
echo "Proteins   : $RELATED_PROTEINS (enabled=$USE_PROTEINS)"
echo "Helixer    : $HELIXER_GFF"

if [[ ! -s "$RAW_GFF" || "$FORCE" == 1 ]]; then
    cd "$OUT_DIR"
    EVIANN_CMD=(eviann.sh -g "$GENOME_FA" -t "$THREADS" -d "$PLOIDY" -r "$READS_LIST" -e "$EVIANN_TRANSCRIPTS" -c "$HELIXER_GFF" --verbose)
    [[ "$USE_PROTEINS" == 1 ]] && EVIANN_CMD+=(-p "$RELATED_PROTEINS")
    [[ "$USE_PROTEINS" == 1 && "$USE_SWISSPROT" == 1 && -s "$SWISSPROT" ]] && EVIANN_CMD+=(-s "$SWISSPROT")
    "${EVIANN_CMD[@]}"
else
    echo "Existing EviAnn GFF found, skipping: $RAW_GFF"
fi
require_file "$RAW_GFF" "EviAnn raw GFF3"

FINAL_GFF="$RAW_GFF"
[[ -s "$FUNCTIONAL_GFF" ]] && FINAL_GFF="$FUNCTIONAL_GFF"
source "$CONDA_SH"
conda activate "$PY_ENV"
PYTHON_BIN="python3"
command -v "$PYTHON_BIN" >/dev/null 2>&1 || PYTHON_BIN="python"
POSTPROCESS_CMD=("$PYTHON_BIN" "$POSTPROCESS_SCRIPT" --genome "$GENOME_FA" --gff3 "$FINAL_GFF" --out-dir "$POST_DIR" --prefix "$PREFIX" --short-cds 300 --gene-te-fraction 0.80 --cds-te-fraction 0.50 --te-gff3 "$TE_GFF3")
"${POSTPROCESS_CMD[@]}"
"$PYTHON_BIN" "$STATS_SCRIPT" --gff3 "$POST_DIR/${PREFIX}.genes.gff3" --prefix "$PREFIX" --out-dir "$POST_DIR/stats"

{
    echo "PSP EviAnn 2n=32 annotation manifest"
    echo "Genome: $GENOME_FA"
    echo "EviAnn reads list: $READS_LIST"
    echo "EviAnn transcript FASTA: $EVIANN_TRANSCRIPTS"
    echo "Related transcript evidence: $RELATED_TRANSCRIPTS"
    echo "Genome-guided PSP transcript FASTA (auxiliary): $EVIDENCE_TRANSCRIPTS"
    echo "Genome-guided PSP transcript GTF (auxiliary): $EVIDENCE_GTF"
    echo "Related proteins: $RELATED_PROTEINS"
    echo "Protein evidence enabled: $USE_PROTEINS"
    echo "Swiss-Prot evidence enabled: $USE_SWISSPROT"
    echo "Protein source PPE: ${RELATED_PROTEIN_SOURCES[0]}"
    echo "Protein source PCAM: ${RELATED_PROTEIN_SOURCES[1]}"
    echo "Ploidy: $PLOIDY"
    echo "Helixer input GFF3: $HELIXER_GFF"
    echo "Final GFF3: $POST_DIR/${PREFIX}.genes.gff3"
    echo "Final CDS: $POST_DIR/${PREFIX}.cds.fa"
    echo "Final protein: $POST_DIR/${PREFIX}.protein.fa"
} > "$OUT_DIR/psp_eviann_manifest.txt"

echo "PSP EviAnn completed: $POST_DIR/${PREFIX}.genes.gff3"
